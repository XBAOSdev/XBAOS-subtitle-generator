/**
 * 用户协议与隐私政策的正文。
 *
 * 为什么放在源码里而不是读 `docs/legal/*.md`：打包后的安装目录里没有 `docs/`，
 * 而这两份文件必须**离线可读**（用户断网时也要能点开看）。写成结构化数据还有一个好处：
 * 排版由组件统一负责，改文案不用碰样式。
 *
 * 维护约定：改这里的文案时，`docs/legal/` 下的草案要同步改 —— 两边不一致比没有更糟。
 * 主体一律写 `XBAOS`，并**始终带上官网**：个人开发者重名太多，只写「XBAOS」指向不明，
 * 官网是唯一能确定「说的是哪一个」的锚点。
 */

export type LegalKey = 'terms' | 'privacy'

export interface LegalTable {
  head: string[]
  rows: string[][]
}

export interface LegalSection {
  heading: string
  /** 正文段落，一条一段 */
  paragraphs?: string[]
  /** 项目符号列表 */
  list?: string[]
  /** 需要逐项对照的内容（目前只有「会联网的功能」用得上） */
  table?: LegalTable
}

export interface LegalDoc {
  key: LegalKey
  title: string
  subtitle: string
  sections: LegalSection[]
}

