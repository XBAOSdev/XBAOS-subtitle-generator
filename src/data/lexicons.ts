export function lexiconById(id: string): Lexicon | undefined {
  return LEXICONS.find((l) => l.id === id)
}

/** 全部词条数（界面上显示「共收录 N 词」用） */
export function lexiconWordCount(l: Lexicon): number {
  return l.core.length + l.extended.length
}
