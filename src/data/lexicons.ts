/**
 * 内置领域词库。
 *
 * 用途：勾选后，词库内容会作为「提示词」注入识别引擎的 initial_prompt，
 * 显著提升专有名词的准确率。
 *
 * 版权规避原则（硬约束，新增词条必须遵守）：
 *   1. 不含任何品牌名、公司名、软件名、作品名 —— 只用通用技术名词与通用文体术语；
 *   2. 人名库只收「常见姓氏」与「复姓」，不收任何具体完整姓名，避免指向真实个人；
 *   3. 成语、规范用词等均为公共领域词汇。
 * 换句话说：所有词条都是「描述某个概念」的通用词，不承载任何主体的识别性权益。
 *
 * 结构说明：
 *   core     —— 勾选后恒定注入（每库 ≤20 词，占用预算稳定可控）
 *   extended —— 只在「深度模式」由两遍策略动态精选后注入：
 *               先跑一遍识别，挑出这段音频里真的出现过的词，再带着它们重跑一次。
 *               这样大词库才不会把提示词预算撑爆。
 *   style    —— 风格描述句。whisper 对提示词的理解是「这是什么样的内容」，
 *               一句自然语言描述比一串孤立的词更有效，且几乎不占预算。
 *   wrapWords —— **只用于断句、绝不进提示词**。放的是这个领域口播里高频出现、
 *               但作为提示词没有价值（甚至干扰）的普通搭配，比如「这一代」
 *               「实际体验」。它们唯一的作用是告诉折行逻辑「这几个字是一个词，
 *               别从中间切开」。勾选该词库才生效，不勾选时完全不参与。
 *
 * 提示词预算与断句词库是两条互不影响的通道：`buildPrompt` 只读 core / extended /
 * style，wrapWords 只在 `applyLineWrap` 里被读 —— 往这里加词永远不会撑爆提示词。
 */

export interface Lexicon {
  id: string
  /** 展示名 */
  name: string
  /** 一句话说明，界面上显示 */
  note: string
  /** 风格描述句，注入在词列表之前 */
  style: string
  /** 核心词，恒定注入 */
  core: string[]
  /** 扩展词，深度模式动态精选 */
  extended: string[]
  /**
   * 断句专用词：勾选该词库后参与折行断点判断，**不进提示词、不影响转录结果**。
   * 只放 2–4 字的普通搭配；单字（如姓氏）不要放进来，切点判断需要至少两个字。
   */
  wrapWords?: string[]
}

