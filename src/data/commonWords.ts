/** 把空格分隔的词串切成去重后的数组 */
function splitWords(raw: string): string[] {
  return Array.from(new Set(raw.split(/\s+/).filter(Boolean)))
}

/**
 * 分组视图。设置页「内置词表」查看器按这个顺序分节展示，也复用这里的计数
 * —— 所以别在别处再抄一份分组名。
 *
 * **全局去重**：同一个词只保留在它首次出现的分组里。不做这一步的话，
 * 各分节词条数之和会大于总词数（有二十几个词跨了两个语类），
 * 弹窗上「共 972 词」而铺开一数 995 个，用户会以为软件算错了。
 */
const seenWords = new Set<string>()

function dedupeAcrossGroups(group: CommonWordGroup): CommonWordGroup {
  return {
    ...group,
    words: group.words.filter((w) => {
      if (seenWords.has(w)) return false
      seenWords.add(w)
      return true
    }),
  }
}

