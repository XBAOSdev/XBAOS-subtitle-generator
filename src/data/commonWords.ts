/**
 * 断句常用词库。
 *
 * 用途只有一个：**判断「切点是不是落在了词内部」**。字幕按宽度硬切时，
 * 中文没有词间空格可依赖，切点会落在「我/们」「标/准」「用/户」之间，
 * 观众看到的是「二进制并不适合我 / 们日常的计算和交流」。
 *
 * 这份词表**不会发送给识别引擎**，对转录内容没有任何影响 —— 它只在
 * 识别完成后的折行/拆条环节被引用，用来挑一个不破坏词的切点。
 *
 * ## 收录原则
 *
 *   1. 只收**口语与讲解里高频出现**的通用词，不收低频书面语；
 *   2. 长度 2–6 字。单字词没有意义（切点判断需要至少两个字才能定义「内部」），
 *      超过 6 字的组合命中率低且超出匹配窗口（见 `lineWrap.ts` 的 `MAX_WORD_ATOMS`）；
 *   3. 不含任何品牌名、公司名、作品名、人名 —— 与 `lexicons.ts` 同一套版权规避原则；
 *   4. 宁可多收常见虚词与搭配（这些恰恰是最容易被切断的），不必追求覆盖专有名词
 *      —— 专有名词交给领域词库。
 *
 * ## 版权说明（重要）
 *
 * 本词表按**现代汉语通用词汇**自行整理，不复制任何词典、教材、词表或语料库的
 * 编排与释义。收录的只是「词」这一级单位的字符串本身：
 *   - 单个词语是语言的公共构成材料，不构成著作权法意义上的作品；
 *   - **成语**（多为古代沿用）已过著作权保护期，可自由收录；
 *   - 刻意不收：商标与品牌名、公司名、影视/音乐/游戏作品名、人物姓名、
 *     歌词与台词片段、任何需要授权的专有名词集合。
 *
 * 换言之：这里只有「哪些字连在一起算一个词」的事实性判断，没有任何来自
 * 他人作品的表达。与 `data/lexicons.ts`（领域词库）遵循同一条红线。
 *
 * ## 维护说明
 *
 * 词表按语类分组，每组一段空格分隔的词串。新增词条直接加进对应分组即可，
 * 重复词由下方去重逻辑吸收，不需要手工排重。
 *
 * 分组是有意义的：设置页的「内置词表」查看器按这里的 `label` 分节展示，
 * 用户能看清哪一类词在起作用。所以**新增分组要给中文名**，别只加词。
 *
 * 规模不是越大越好，但**漏一个词就等于允许在这一处切错**（切点枚举时该位置
 * 拿不到 −8000 的惩罚，只剩宽度项竞争）。因此宁可多收高频搭配，也不追求精选。
 * 词表是 `Set` 查询，规模对性能无影响。
 */

export interface CommonWordGroup {
  id: string
  /** 查看器里显示的类别名 */
  label: string
  words: string[]
}

